<?php
namespace EzMvc;

/**
 * A single mysqli connection plus transaction/time helpers. This is the one
 * real implementation; StaticDatabase is a static facade that delegates here.
 */
class Database {
    private ?\mysqli $connection = null;

    /** Connects with utf8mb4 and makes every mysqli error throw. */
    public function __construct(string $host, string $user, #[\SensitiveParameter] ?string $pass, string $db) {
        mysqli_report(MYSQLI_REPORT_ERROR | MYSQLI_REPORT_STRICT);
        $this->connection = new \mysqli($host, $user, $pass, $db);
        $this->connection?->set_charset('utf8mb4');
    }

    /** The underlying mysqli connection, e.g. for Entity::bindDefaultConnection(). */
    public function getConnection() {
        return $this->connection;
    }

    /** Starts a read-write transaction; prefer runTransaction(). */
    public function beginTransaction() {
        $this->connection?->begin_transaction(MYSQLI_TRANS_START_READ_WRITE);
    }

    /** Commits the transaction begun with beginTransaction(). */
    public function commit() {
        $this->connection?->commit();
    }

    /** Discards the transaction begun with beginTransaction(). */
    public function rollback() {
        $this->connection?->rollback();
    }

    /**
     * Runs $fn inside a transaction: commits its return value, or rolls back
     * and rethrows if $fn throws. $fn receives this Database. Saves the
     * begin/try/commit/rollback boilerplate for the common case.
     * @return mixed whatever $fn returns
     */
    public function runTransaction(callable $fn) {
        $this->beginTransaction();
        try {
            $result = $fn($this);
            $this->commit();
            return $result;
        } catch (\Throwable $e) {
            $this->rollback();
            throw $e;
        }
    }

    /**
     * All rows of a parameterized SELECT, as an array of associative rows
     * (empty array when none). The safe way to run ad-hoc SQL the ORM doesn't
     * model — bind values as ? placeholders, never string-concatenate them.
     * @param mixed[] $params
     * @return array[]
     */
    public function fetchAll(string $sql, array $params = []): array {
        return $this->run($sql, $params)->get_result()->fetch_all(MYSQLI_ASSOC);
    }

    /**
     * The first row of a parameterized SELECT as an associative array, or null
     * when there are none.
     * @param mixed[] $params
     */
    public function fetchOne(string $sql, array $params = []): ?array {
        return $this->run($sql, $params)->get_result()->fetch_assoc();
    }

    /**
     * The first column of the first row of a parameterized SELECT (a single
     * scalar), or null when there are none. For counts, sums, one id, etc.
     * @param mixed[] $params
     * @return mixed
     */
    public function fetchColumn(string $sql, array $params = []) {
        $row = $this->run($sql, $params)->get_result()->fetch_row();
        return $row[0] ?? null;
    }

    /**
     * Runs a parameterized write (INSERT/UPDATE/DELETE) and returns the number
     * of affected rows.
     * @param mixed[] $params
     */
    public function execute(string $sql, array $params = []): int {
        return $this->run($sql, $params)->affected_rows;
    }

    /** The auto-increment id generated by the most recent INSERT. */
    public function lastInsertId(): int|string {
        return $this->connection->insert_id;
    }

    /** Minutes are signed: a negative $offsetMinutes returns a past time. */
    public function getTime(int $offsetMinutes = 0) {
        return $this->fetchColumn('select date_add(now(), interval ? minute)', [$offsetMinutes]);
    }

    /**
     * Prepares $sql, binds $params, executes, and returns the statement.
     * Bind types are inferred from each value (int/bool -> i, float -> d,
     * everything else incl. null -> s), which covers ordinary scalar params;
     * reach for the raw connection if you need explicit blob/decimal binding.
     * @param mixed[] $params
     */
    private function run(string $sql, array $params): \mysqli_stmt {
        $stmt = $this->connection->prepare($sql);
        if ($params) {
            $types = '';
            foreach ($params as $p) {
                $types .= is_int($p) || is_bool($p) ? 'i' : (is_float($p) ? 'd' : 's');
            }
            $stmt->bind_param($types, ...$params);
        }
        $stmt->execute();
        return $stmt;
    }
}
